/**
 * 虚拟广场 · 话题的「发光物件」（纯函数，零随机、可复现）。
 *
 * ## 为什么要有一件「东西」摆在人群中间
 *
 * owner 的原话：「话题要做可视化，要让人一眼就看出来是干什么的，
 * 人围着就好像这个话题是一个奇珍异宝一样，发光 —— 这样才能让影子合理。」
 *
 * 这一条同时修掉了我之前设计里的两个真问题：
 *
 *   ① **影子为什么合理**。上一版是「整个广场一盏灯」（最热那一场），
 *      于是离灯远的簇，十几个人的影子互相平行地甩向同一个方向 ——
 *      那不像投影，像一片被吹倒的草。
 *      现在**每个话题自己发光**，人围着它站、影子从它往外辐射：
 *      每一簇的光影自己就自洽了，不需要任何解释。
 *
 *   ② **点它的理由**。一个话题原本只是一个虚线圈 + 一行标题；
 *      现在它中间立着一件**该话题自己的物件**（房子 / 眼镜 / 咖啡杯…），
 *      发着光，人围着它 —— 一眼就看出这场在聊什么。
 *
 * ## 物件从哪来（零模型、可解释）
 *
 * 不用 AI 生成、不用图片素材：**由标题里的关键词命中一张物件表**，
 * 命不中就用「话题类别」的兜底物件。全部是设计系统允许的几何形状
 * （圆 / 方 / 线 / 弧），与站内其它插画同一套语言。
 *
 * 命中的过程是可复现的：同一标题永远得到同一件物件 —— 评委刷新看到的
 * 广场不会变，这与 `crowd.ts` / `light.ts` 的硬约束一致。
 */

/** 物件形状的原子。全部是几何原语，不用位图。 */
export type RelicShape =
  | "house"      // 房子（买房 / 搬家 / 学区）
  | "coin"       // 钱（薪资 / 存款 / 借钱）
  | "cup"        // cup（咖啡店 / 开店）
  | "book"       // 书（考研 / 读博 / 上学）
  | "screen"     // 屏幕（自媒体 / 独立开发 / 摸鱼）
  | "glass"      // 镜片（近视 / 健康）
  | "pill"       // 药（保健品 / 医疗）
  | "ring"       // 环（相亲 / 婚姻 / 感情）
  | "heart"      // 心（情绪 / 焦虑 / 关系）
  | "city"       // 城市（县城 / 一线 / 搬家）
  | "clock"      // 表（加班 / 时间 / 身体）
  | "people";    // 人（父母 / 孩子 / 家人）

export interface Relic {
  /** 决定画哪个形状 */
  shape: RelicShape;
  /** 为什么是这件（供详情面板与自检用的可解释说明） */
  reason: string;
  /** 光晕强度 0..1：热度越高越亮（热度是布局层已有的 size，不新造数字） */
  intensity: number;
}

/**
 * 关键词 → 物件。顺序即优先级：越靠前越具体。
 *
 * ⚠️ 加新词条时必须同时加一条自检断言（见 `check-square-relic.mjs`），
 *    否则「命不中」与「命错了」都看不出来。
 */
const RELIC_HINTS: Array<{ shape: RelicShape; re: RegExp; why: string }> = [
  // ⚠️ 顺序即优先级，而且**顺序被自检逐条守着**（check-square-relic.mjs 的②节）。
  //
  // 两条已经踩过的坑：
  //   · 「存款 50 万，是先买车还是先还房贷」曾被判成「房子」——
  //     因为 house 排在 coin 前面，而标题里有「房贷」。但这场讨论的核心是
  //     **钱怎么分**（车 vs 房贷），不是房子。所以 coin 必须排在 house 前面。
  //   · 「副业做自媒体」曾被判成「咖啡杯」—— 因为 cup 的正则里含「副业」。
  //     但「副业」本身不指向咖啡店，它只说明这不是主业。已从 cup 里删掉。
  //
  // 一句话原则：**谁更具体谁在前。**「房贷」是钱的一种形态，「自媒体」是屏幕的一种。
  // ⚠️ coin 里**不含**收入词（月薪 / 薪资 / 年薪 / 工资 / 收入）——
  //   它们是背景，不是议题。「月薪两万，在一线城市该不该买房」的议题是**房子**
  //   （能不能负担、该不该买），不是「钱」；把它判成「钱」会让人看不出在聊什么。
  //   自检的②节第一次就抓到了这一条。
  //   保留的全是**钱的用法**：怎么存、怎么借、怎么还、花在哪。
  { shape: "coin", re: /(存款|借钱|还房贷|房贷|首付|彩礼|买车|车贷|消费|省钱|理财|基金|股票|投资|债务|贷款)/, why: "钱" },
  { shape: "house", re: /(买房|房价|学区|搬家|老破小|同住|房子|居住|租房)/, why: "房子" },
  { shape: "cup", re: /(咖啡|开店|创业|生意|店铺|门店)/, why: "咖啡 / 店铺" },
  { shape: "book", re: /(考研|读博|上岸|学历|学校|读书|国际学校|考公|公务员|事业单位|应届|实习)/, why: "书 / 学业" },
  { shape: "clock", re: /(加班|辞职|离职|跳槽|转行|优化|裁员|身体|报警|十点|时间|摸鱼)/, why: "工时 / 时间" },
  { shape: "glass", re: /(近视|离焦镜|眼睛|视力|眼镜)/, why: "镜片" },
  { shape: "pill", re: /(保健品|养生|医疗|药|健康|减肥|睡眠|失眠)/, why: "保健品 / 药" },
  { shape: "ring", re: /(相亲|婚姻|离婚|结婚|婚礼|恋爱|分手|朋友|对象)/, why: "关系" },
  { shape: "heart", re: /(焦虑|抑郁|情绪|心理|自卑|孤独|内耗|压力|意义|崩溃|迷茫|羞耻)/, why: "情绪" },
  { shape: "city", re: /(城市|县城|一线|搬家|户口|落户|国际|外地)/, why: "城市" },
  { shape: "screen", re: /(自媒体|独立开发|程序员|代码|AI|人工智能|互联网|产品|技术|软件|摸鱼|网约车|家政)/, why: "屏幕 / 电脑" },
  { shape: "people", re: /(父母|孩子|家人|老人|养老|育儿|亲戚|家人|老了|接来)/, why: "家人" },
];

/**
 * 给一个标题选物件。
 *
 * @param title 话题标题
 * @param size  布局层给的卡片尺寸 —— 只用来定光晕强度（热度代理），不新造数字
 */
export function relicOf(title: string, size: number): Relic {
  const text = String(title ?? "");
  for (const h of RELIC_HINTS) {
    if (h.re.test(text)) {
      return { shape: h.shape, reason: "标题命中「" + h.why + "」", intensity: intensityFrom(size) };
    }
  }
  // 一件都没命中：给一个中性的「话题」物件（环）。
  // 不返回 null —— 广场中央空着会比放错一件东西更糟：人围着空气站更说不通。
  return { shape: "ring", reason: "没有具体物件线索，用中性的「话题」环", intensity: intensityFrom(size) };
}

/**
 * 尺寸 → 光晕强度 0.45..1。
 *
 * 不做对数或幂次映射：`size` 本身已经是布局层算好的热度序，
 * 这里只做线性归一到 0.45 以上 —— **低于 0.45 的光晕在深色地面上看不见**（实测），
 * 而「看不见光」会让影子失去来源、整套设计垮掉。
 */
function intensityFrom(size: number): number {
  const t = Math.min(Math.max((size - 130) / (320 - 130), 0), 1);
  return 0.45 + 0.55 * t;
}

/** 人围着物件站的半径比例（物件本身多大）。 */
export const RELIC_RADIUS_RATIO = 0.3;

